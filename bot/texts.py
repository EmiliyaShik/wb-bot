def module_title(name: str) -> str:
    """Человеческое название модуля из конфига."""
    info = config.modules().get(name)
    return info.title if info and info.title else name


# --- подстановка в разметку ---


class Safe(str):
    """Текст, который бот собрал сам: разметка внутри него намеренная.

    Пометка нужна двум вещам: куску, который уже заполнил `fill`, и склейке
    нескольких таких кусков в одно сообщение. Чужая строка `Safe` не бывает:
    сделать её не из чего, кроме как из наших же заполненных шаблонов, и
    каждое такое место видно в файле глазами.
    """


def fill(template: str, **fields: Any) -> Safe:
    """Заполняет шаблон HTML, экранируя всё, что не помечено `Safe`.

    Граница стоит на подстановке, а не у каждого поля. Подставляется наименование
    организации, которое клиент пишет руками, адрес из чужого справочника, имя
    модуля прямо из аргумента команды, номер платежа, сырой ответ Wildberries из
    `last_error` и запись журнала. Угловая скобка в таком значении либо
    становится нашей же разметкой (ссылка в личке, от собственного бота), либо
    ломает сообщение целиком, и человек не получает его вообще. Автор следующего
    шаблона про экранирование не вспомнит, поэтому вспоминать должна подстановка.

    Экранируется сообщение, а не данные: в базе и в книгах Excel наименование
    лежит так, как его написали.

    Результат помечен `Safe`: он уже заполнен, и второй проход по нему показал
    бы наши собственные теги текстом.
    """
    ready = {
        name: value if isinstance(value, Safe) else html.escape(str(value), quote=True)
        for name, value in fields.items()
    }
    return Safe(template.format(**ready))
